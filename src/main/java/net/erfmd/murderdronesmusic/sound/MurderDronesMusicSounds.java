    private static RegistryKey<JukeboxSong> registerMusicDisc(String name) {
        return RegistryKey.of(RegistryKeys.JUKEBOX_SONG, Identifier.of(MurderDronesMusic.MOD_ID, name));
    }

    private static SoundEvent registerSoundEvent(String name) {
        return Registry.register(Registries.SOUND_EVENT, Identifier.of(MurderDronesMusic.MOD_ID, name),
                SoundEvent.of(Identifier.of(MurderDronesMusic.MOD_ID, name)));
    }

